"""Package a run into deliverables: Navigator layer, markdown report, zip bundle."""

from __future__ import annotations

import io
import json
import re
import zipfile
from typing import Any

from .convert import TARGETS
from .models import FinalRule, RunResult

NAVIGATOR_COLORS = {"validated": "#2e8b57", "needs_review": "#e9a23b", "failed": "#c0392b"}


def slugify(text: str) -> str:
    """File-system-safe name from a rule title."""
    s = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return s[:80] or "rule"


def navigator_layer(result: RunResult) -> dict[str, Any]:
    """ATT&CK Navigator layer (v4.5 format) colouring covered techniques."""
    techniques: dict[str, dict[str, Any]] = {}
    for rule in result.rules:
        for tid in rule.attack_technique_ids:
            tid_u = tid.upper()
            entry = techniques.setdefault(tid_u, {"techniqueID": tid_u, "score": 0, "color": NAVIGATOR_COLORS[rule.status], "comment": "", "enabled": True, "showSubtechniques": True})
            entry["score"] += 1
            entry["comment"] = (entry["comment"] + "; " if entry["comment"] else "") + f"{rule.title} [{rule.status}]"
            # Validated beats needs_review beats failed when several rules share a technique.
            if rule.status == "validated":
                entry["color"] = NAVIGATOR_COLORS["validated"]
    return {
        "name": f"RuleSmith: {result.report.title}"[:100],
        "versions": {"attack": "18", "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": f"Detections generated by RuleSmith from '{result.report.title}' on {result.created_at[:10]}.",
        "techniques": list(techniques.values()),
        "gradient": {"colors": ["#ffffff", "#2e8b57"], "minValue": 0, "maxValue": 3},
        "legendItems": [{"label": k.replace("_", " "), "color": v} for k, v in NAVIGATOR_COLORS.items()],
        "showTacticRowBackground": True,
        "selectTechniquesAcrossTactics": True,
    }


def markdown_report(result: RunResult) -> str:
    """Human-readable summary with evidence links for each rule."""
    stats = result.stats()
    lines = [
        f"# RuleSmith detection pack: {result.report.title}",
        "",
        f"Generated {result.created_at[:19]}Z · run `{result.run_id}`",
        "",
        "## Summary",
        "",
        result.report.summary,
        "",
        f"- Threat actors: {', '.join(result.report.threat_actors) or 'n/a'}",
        f"- Malware families: {', '.join(result.report.malware_families) or 'n/a'}",
        f"- Behaviours extracted: {stats['behaviors']} · rules: {stats['rules']} (validated {stats['validated']}, needs review {stats['needs_review']}, failed {stats['failed']})",
        f"- Test results: positive recall {stats['positive_recall']}, negative precision {stats['negative_precision']}, benign-baseline hits {stats['benign_hits']}",
        "- Models: " + ", ".join(f"{tier}={model}" for tier, model in result.models.items()),
        f"- Tokens: {stats['prompt_tokens']} in / {stats['completion_tokens']} out · est. cost ${stats['cost_usd']:.4f}",
        "",
        "## Rules",
        "",
    ]
    for rule in result.rules:
        v = rule.validation
        lines += [
            f"### {rule.title}",
            "",
            f"Status: **{rule.status}** · ATT&CK: {', '.join(rule.attack_technique_ids) or 'n/a'} · iterations: {len(rule.history)}",
            "",
            f"Validation: {v.summary()}",
            "",
        ]
        for h in rule.history:
            lines.append(f"- {h.phase} #{h.iteration}: {h.summary}" + (f" — {h.change_summary}" if h.change_summary else ""))
        if rule.redteam_analysis:
            lines += ["", f"Red-team analysis: {rule.redteam_analysis}"]
        lines += ["", "```yaml", rule.sigma_yaml.strip(), "```", ""]
        for target, query in rule.conversions.items():
            lines += [f"<details><summary>{TARGETS[target]['label']}</summary>", "", "```", query, "```", "", "</details>", ""]
    if result.plan.skipped:
        lines += ["## Behaviours not turned into rules", ""] + [f"- {s}" for s in result.plan.skipped] + [""]
    lines += ["## Evidence", ""]
    for b in result.report.behaviors:
        lines.append(f"- **{b.id}** {b.attack_technique_id} · {b.description}\n  > {b.evidence}")
    if result.warnings:
        lines += ["", "## Warnings", ""] + [f"- {w}" for w in result.warnings]
    return "\n".join(lines) + "\n"


def build_zip(result: RunResult) -> bytes:
    """Zip bundle: rules/, queries/, tests/, navigator layer, report, raw run JSON."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for rule in result.rules:
            slug = slugify(rule.title)
            zf.writestr(f"rules/{slug}.yml", rule.sigma_yaml)
            for target, query in rule.conversions.items():
                zf.writestr(f"queries/{slug}.{TARGETS[target]['ext']}", query + "\n")
            tests = "\n".join(json.dumps({"id": t.id, "label": t.label, "description": t.description, "event": t.event}) for t in rule.tests)
            zf.writestr(f"tests/{slug}.jsonl", tests + "\n")
        zf.writestr("navigator_layer.json", json.dumps(navigator_layer(result), indent=2))
        zf.writestr("report.md", markdown_report(result))
        zf.writestr("run.json", result.model_dump_json(indent=2))
    return buf.getvalue()


def rule_summary(rule: FinalRule) -> dict[str, Any]:
    """Compact dict for list views in the UI."""
    return {
        "candidate_id": rule.candidate_id,
        "title": rule.title,
        "status": rule.status,
        "techniques": rule.attack_technique_ids,
        "iterations": len(rule.history),
        "validation": rule.validation.summary(),
    }
